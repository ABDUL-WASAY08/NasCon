import 'dart:typed_data';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../models/order.dart';

/// Generates a genuine PDF receipt for a confirmed order.
///
/// The same bytes are used for download and for sharing/printing, so the user
/// never receives a "downloaded" file that does not exist.
abstract final class ReceiptPdf {
  static Future<Uint8List> build(Order order) async {
    final doc = pw.Document();
    final currency = order.currency;

    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        build: (context) => pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'NaSCon \u201926',
              style: pw.TextStyle(
                fontSize: 22,
                fontWeight: pw.FontWeight.bold,
              ),
            ),
            pw.Text('Payment receipt'),
            pw.SizedBox(height: 16),
            _row('Order ID', order.id),
            _row('Receipt', 'RCPT-${order.id.toUpperCase()}'),
            _row('Status', order.status.label),
            _row('Payment', order.paymentStatus.label),
            _row('Issued', (order.createdAt ?? DateTime.now()).toString()),
            if (order.paymentReference != null)
              _row('Reference', order.paymentReference!),
            pw.SizedBox(height: 20),
            pw.TableHelper.fromTextArray(
              headers: const ['Item', 'Qty', 'Unit', 'Line total'],
              data: [
                for (final item in order.items)
                  [
                    item.variantName == null
                        ? item.productName
                        : '${item.productName} (${item.variantName})',
                    '${item.quantity}',
                    '$currency ${item.unitPrice.toStringAsFixed(2)}',
                    '$currency ${item.lineTotal.toStringAsFixed(2)}',
                  ],
              ],
            ),
            pw.SizedBox(height: 16),
            _row('Subtotal', '$currency ${order.subtotal.toStringAsFixed(2)}'),
            if (order.discount > 0)
              _row('Discount', '-$currency ${order.discount.toStringAsFixed(2)}'),
            _row('Tax', '$currency ${order.tax.toStringAsFixed(2)}'),
            _row('Shipping', '$currency ${order.shipping.toStringAsFixed(2)}'),
            pw.Divider(),
            pw.Text(
              'Total: $currency ${order.total.toStringAsFixed(2)}',
              style: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 14),
            ),
            pw.SizedBox(height: 24),
            pw.Text(
              'This receipt was generated by the NaSCon mobile app.',
              style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
            ),
          ],
        ),
      ),
    );

    return doc.save();
  }

  static pw.Widget _row(String label, String value) => pw.Padding(
    padding: const pw.EdgeInsets.only(bottom: 4),
    child: pw.Row(
      children: [
        pw.SizedBox(
          width: 110,
          child: pw.Text(label, style: const pw.TextStyle(fontSize: 10)),
        ),
        pw.Expanded(
          child: pw.Text(value, style: const pw.TextStyle(fontSize: 11)),
        ),
      ],
    ),
  );
}
